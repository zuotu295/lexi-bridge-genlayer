import assert from 'node:assert/strict';
import { makeDeployment, read, signer, submit } from './studionet.mjs';
const [host, guest, outsider] = await Promise.all([signer(), signer(), signer()]);
const { address, evidence } = await makeDeployment(host, new URL('../contracts/lexi_bridge.py', import.meta.url), [], 'LexiBridge');
console.log('ADDRESS', address);
const board = () => read(address,'board');
const joined = await submit(guest,address,'join');
const invalid = await submit(host,address,'move',['colx','cold']);
const afterInvalid = await board();
assert.deepEqual(afterInvalid.track,['cold']);
assert.equal(afterInvalid.turn.toLowerCase(),host.account.address.toLowerCase());
assert.equal(afterInvalid.attempts[0].verdict,'UNKNOWN_WORD');
const unauthorized = await submit(outsider,address,'move',['cord','cold'],'wrong wallet',/other player/);
const first = await submit(host,address,'move',['cord','cold']);
const intermediate = await board();
assert.equal(intermediate.turn.toLowerCase(),guest.account.address.toLowerCase());
const solved = await submit(guest,address,'move',['card','cord']);
const finished = await board();
assert.equal(finished.phase,'SOLVED');
assert.deepEqual(finished.track,['cold','cord','card']);
const closed = await submit(host,address,'move',['ward','card'],'terminal repeat',/not playing/);
assert.deepEqual(await board(),finished);
console.log('EVIDENCE', JSON.stringify({address,deployment:evidence,joined,invalid,unauthorized,first,solved,closed,afterInvalid,finished}));
